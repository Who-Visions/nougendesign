#!/usr/bin/env python3
"""variant_plans.py — candidate design variants as mutation plans
(Claude Design reversal, Module 10, fleet-safe).

Claude Design's tweak panel applies on close, with no undo — a tool
that silently commits breaks the fleet's candidates-vs-locks rule.
This is the fleet-safe half: a variant is a *stored plan* in the
compiler's own mutations shape ({selector, change} prose pairs),
kept next to the package it targets, comparable and diffable, and
applied ONLY when Dave locks it. Nothing in this tool applies a
plan; there is deliberately no apply command. Locking a variant is a
human act recorded outside the plan; merging a locked plan's
mutations into a package's design.json goes through the normal
reviewed-spec flow of tools/nougendesigns.py.

Plan file shape (JSON):

  {
    "variant": "boards-stale-quiet",        // kebab-case id
    "status": "candidate",                   // always "candidate"
    "package": "nougenai-brand",             // package it mutates
    "surface": "fleet-boards",               // Dave-facing surface
    "summary": "One line: what the variant does.",
    "lock_effect": "One line: what Dave is locking if he picks it.",
    "mutations": [{"selector": "...", "change": "..."}, ...]
  }

Commands:

  python3 tools/variant_plans.py validate designs/nougenai-brand/variants
  python3 tools/variant_plans.py diff designs/nougenai-brand/mutations.json \
      designs/nougenai-brand/variants/boards-stale-quiet.json
  python3 tools/variant_plans.py index designs/nougenai-brand/variants

`index` (re)writes INDEX.md in the variants dir from the plans —
generated, never hand-edited. Exit code 1 on any validation error or,
for diff, it simply reports; diff always exits 0.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REQUIRED = ("variant", "status", "package", "surface", "summary", "lock_effect", "mutations")
KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def load_plan(path):
    return json.loads(Path(path).read_text())


def mutations_of(data):
    """A plan file wraps mutations; a bare mutations.json is the list itself."""
    if isinstance(data, list):
        return data
    return data.get("mutations", [])


def validate_plan(path):
    errors = []
    try:
        data = load_plan(path)
    except (json.JSONDecodeError, OSError) as exc:
        return [f"{path}: unreadable ({exc})"]
    if not isinstance(data, dict):
        return [f"{path}: a variant plan must be a JSON object wrapping its mutations"]
    for key in REQUIRED:
        if key not in data:
            errors.append(f"{path}: missing required key '{key}'")
    if data.get("status") != "candidate":
        errors.append(f"{path}: status must be 'candidate' — plans never self-apply "
                      "and never claim to be locked")
    if "variant" in data and not KEBAB.match(str(data["variant"])):
        errors.append(f"{path}: variant id '{data['variant']}' is not kebab-case")
    muts = data.get("mutations")
    if not isinstance(muts, list) or not muts:
        errors.append(f"{path}: mutations must be a non-empty list")
    else:
        for i, m in enumerate(muts):
            if not isinstance(m, dict) or not str(m.get("selector", "")).strip() \
                    or not str(m.get("change", "")).strip():
                errors.append(f"{path}: mutation {i} needs a non-empty selector and change")
    return errors


def collect_plans(target):
    target = Path(target)
    if target.is_dir():
        return sorted(target.glob("*.json"))
    return [target]


def diff_mutations(before, after):
    """Selector-level diff between two mutation lists."""
    b = {m["selector"]: m["change"] for m in before}
    a = {m["selector"]: m["change"] for m in after}
    out = {"added": [], "removed": [], "changed": [], "unchanged": []}
    for sel in sorted(a):
        if sel not in b:
            out["added"].append({"selector": sel, "change": a[sel]})
        elif a[sel] != b[sel]:
            out["changed"].append({"selector": sel, "before": b[sel], "after": a[sel]})
        else:
            out["unchanged"].append(sel)
    for sel in sorted(b):
        if sel not in a:
            out["removed"].append({"selector": sel, "change": b[sel]})
    return out


def render_index(plans):
    lines = [
        "# Candidate variants — stored plans, applied only on Dave's lock",
        "",
        "Generated by `tools/variant_plans.py index`. Do not hand-edit.",
        "",
        "Every plan below is a **candidate**: stored, comparable, and "
        "inert. Nothing here applies on view, on close, or on refresh. "
        "A variant takes effect only when Dave names it as locked; the "
        "lock is recorded with the surface's own change log, and the "
        "plan's mutations then merge through the reviewed-spec flow.",
        "",
    ]
    for data in plans:
        lines += [
            f"## {data['variant']}",
            "",
            f"- Surface: `{data['surface']}` · Package: `{data['package']}` "
            f"· Mutations: {len(data['mutations'])}",
            f"- What it does: {data['summary']}",
            f"- **Locking it means:** {data['lock_effect']}",
            "",
            "| Selector | Change |",
            "|---|---|",
        ]
        for m in data["mutations"]:
            change = str(m["change"]).replace("|", "\\|")
            lines.append(f"| `{m['selector']}` | {change} |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("validate"); p.add_argument("target")
    p = sub.add_parser("diff"); p.add_argument("before"); p.add_argument("after")
    p = sub.add_parser("index"); p.add_argument("target")
    args = parser.parse_args()

    if args.command == "validate":
        errors = []
        for path in collect_plans(args.target):
            errors += validate_plan(path)
        for err in errors:
            print(err, file=sys.stderr)
        print(f"validate: {len(collect_plans(args.target))} plan(s), {len(errors)} error(s)")
        return 1 if errors else 0

    if args.command == "diff":
        result = diff_mutations(mutations_of(load_plan(args.before)),
                                mutations_of(load_plan(args.after)))
        print(json.dumps(result, indent=2))
        return 0

    if args.command == "index":
        target = Path(args.target)
        plans = [load_plan(p) for p in collect_plans(target)]
        out = target / "INDEX.md" if target.is_dir() else target.parent / "INDEX.md"
        out.write_text(render_index(plans))
        print(f"index: {len(plans)} plan(s) → {out}")
        return 0

    return 2


if __name__ == "__main__":
    raise SystemExit(main())
